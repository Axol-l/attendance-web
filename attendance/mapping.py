# 三、排除人员的默认规则
# ============================================================================
#
# 占位账号（钉钉里挂着的系统集成账号）的特征：
#     考勤组 = 「未加入考勤组」  且  无部门  且  无工号
# 这类行全月无任何打卡与出勤数据，混进报表只会多出一堆空行。
#
# ⚠️ 三条踩过的教训（都写进这里，避免后人重踩）：
#
#   教训一：**不能"见到某考勤组就整组排除"**。
#           「未加入考勤组」里混着真实员工 —— 实测有人当月有 13 天真实出勤
#           与完整打卡记录。整组排除会直接丢真实数据。
#           ⇒ 所以默认严格度是 no_dept：必须同时"无部门"才排除。
#
#   教训二：**不能按"全月无数据"排除**。
#           实测有真实员工整月无打卡（产假/陪产假中、长期出差、高管不打卡），
#           桌面版基线报表里这些人是**保留**的。按无数据排除会让月报漏人。
#           ⇒ 所以 exclude_if_no_data 默认关闭。
#
#   教训三：**不要在代码里硬编码真实员工姓名**。
#           桌面版写的是 `if name == '某某': pass`，本项目第一版把该姓名
#           放进了默认配置 —— 这既是隐私泄露（员工姓名进代码库与镜像），
#           也是脆弱的（换个人就漏）。
#           ⇒ 默认名单留空，改由结构化规则命中；确有需要时由管理员在
#              「考勤规则配置」页自行填写。

DEFAULT_EXCLUDED_ATTEND_GROUPS = ['未加入考勤组']

# 占位账号严格度：
#   'no_dept'        —— 考勤组命中 **且 无部门**            → 推荐
#   'no_dept_no'     —— 考勤组命中 **且 无部门 且 无工号**   → 更严格
#   'group_only'     —— 只要考勤组命中就排除（⚠️ 会误伤真人，不建议）
#   'name_only'      —— 只按姓名名单排除，忽略考勤组规则
#
# ⚠️ 「无部门」是承重条件，不能省：实测「未加入考勤组」里的真实员工
#    都带部门信息，而占位账号不带。
DEFAULT_EXCLUDE_MODE = 'no_dept'

